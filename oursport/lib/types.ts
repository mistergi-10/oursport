  startsAt: string;
  description: string | null;
  capacity: number;
  attendeeCount: number;
  spotsLeft: number;
  isAttending: boolean;
  isCreator: boolean;
  creatorUserId: string;
  creatorName: string;
  waitlistCount: number;
